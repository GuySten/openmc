#!/usr/bin/env python3
"""Generate openmc/data/np_pwa93.txt from the NN-OnLine service.

The file tabulates the neutron-proton elastic differential cross section of
the Nijmegen partial-wave analysis PWA93 (V. G. J. Stoks et al., Phys. Rev.
C 48, 792 (1993)) in the center-of-mass system, as computed by
https://nn-online.org (program NNobs1, observable DSG).

The angle is the center-of-mass scattering angle of the neutron. PWA93
includes the magnetic-moment interaction, whose forward spike is not part
of the nuclear cross section measured in transmission; the table therefore
starts at 1 degree and the value there is used down to 0 degrees.

Usage: generate_np_pwa93.py [output.txt]
"""
import sys
import re
import urllib.request
from pathlib import Path

import numpy as np

URL = ('https://nn-online.org/NN/nn.php?program=NNobs1&s=1&r=2&obs1=DSG'
       '&tlab={energy}&f=0&amin={amin}&amax={amax}&aint={aint}')

ENERGIES = list(range(20, 50, 2)) + list(range(50, 201, 5))
ANGLES = [float(a) for a in range(1, 180)] + [179.99]


def fetch(energy, amin, amax, aint):
    url = URL.format(energy=energy, amin=amin, amax=amax, aint=aint)
    with urllib.request.urlopen(url, timeout=120) as f:
        text = re.sub(r'<[^>]*>', '', f.read().decode())
    rows = {}
    started = False
    for line in text.splitlines():
        if 'observable [mb]' in line:
            started = True
            continue
        m = re.match(r'\s*([0-9.]+)\s+([.0-9D+-]+)\s*$', line)
        if started and m:
            rows[float(m.group(1))] = float(m.group(2).replace('D', 'E'))
    return rows


def main(output):
    table = []
    for energy in ENERGIES:
        rows = fetch(energy, 1, 179, 1)
        rows.update(fetch(energy, 179.99, 179.99, 1))
        table.append([rows[a] for a in ANGLES])
    table = np.array(table)
    with open(output, 'w') as f:
        f.write('# Neutron-proton elastic scattering, Nijmegen PWA93\n')
        f.write('# V. G. J. Stoks, R. A. M. Klomp, M. C. M. Rentmeester, and\n'
                '# J. J. de Swart, Phys. Rev. C 48, 792 (1993)\n')
        f.write('# Computed with NN-OnLine (https://nn-online.org), program '
                'NNobs1, observable DSG\n')
        f.write('# Generated by tools/data/generate_np_pwa93.py\n')
        f.write('# First row: neutron center-of-mass scattering angle in '
                'degrees\n')
        f.write('# Following rows: laboratory neutron energy in MeV, then '
                'dsigma/dOmega in mb/sr\n')
        f.write('0 ' + ' '.join(f'{a:g}' for a in ANGLES) + '\n')
        for energy, row in zip(ENERGIES, table):
            f.write(f'{energy} ' + ' '.join(f'{x:.5g}' for x in row) + '\n')


if __name__ == '__main__':
    default = Path(__file__).parents[2] / 'openmc/data/np_pwa93.txt'
    main(sys.argv[1] if len(sys.argv) > 1 else default)
